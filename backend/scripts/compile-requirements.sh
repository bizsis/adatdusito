#!/usr/bin/env bash
# Regenerate backend/requirements.lock (runtime) and backend/requirements-test.lock
# (test-only additions) with uv, for the image interpreter (CPython 3.12, Linux x86_64).
#
# Existing pins are kept: uv prefers the versions already in the output files,
# so only packages whose inputs changed move. To upgrade one package on purpose:
#   UPGRADE="starlette fastapi" backend/scripts/compile-requirements.sh
# Requires uv (https://docs.astral.sh/uv/). Verify afterwards with
# backend/scripts/check-requirements.sh and the backend test suite.
set -euo pipefail
cd "$(dirname "$0")/.."

args=(--python-version 3.12 --python-platform x86_64-manylinux_2_28 --quiet --no-strip-extras)
for package in ${UPGRADE:-}; do args+=(--upgrade-package "$package"); done

uv pip compile requirements.txt -o requirements.lock "${args[@]}" \
  --custom-compile-command "backend/scripts/compile-requirements.sh"

# Full test closure constrained by the runtime lock, then keep only the extras.
full="$(mktemp)"
trap 'rm -f "$full"' EXIT
grep -v '^#' requirements-test.lock 2>/dev/null > "$full" || true
uv pip compile requirements-test.in -c requirements.lock -o "$full" "${args[@]}" --no-header

python3 - "$full" <<'PY'
import re, sys
def pins(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^([A-Za-z0-9_.\-]+)(?:\[[^\]]*\])?==(\S+)", line)
        if m:
            out[re.sub(r"[-_.]+", "-", m.group(1)).lower()] = (m.group(1), m.group(2))
    return out
runtime, full = pins("requirements.lock"), pins(sys.argv[1])
for key, (name, version) in full.items():
    if key in runtime and runtime[key][1] != version:
        sys.exit(f"test resolution changed runtime pin {name}: {runtime[key][1]} -> {version}")
extra = sorted((n, v) for k, (n, v) in full.items() if k not in runtime)
with open("requirements-test.lock", "w", encoding="utf-8") as f:
    f.write("# Test-only additions to requirements.lock (never installed in images).\n")
    f.write("# Generated by backend/scripts/compile-requirements.sh from requirements-test.in.\n")
    f.write("# Install with: pip install --no-deps -r requirements.lock -r requirements-test.lock\n")
    for name, version in extra:
        f.write(f"{name}=={version}\n")
PY
echo "requirements.lock and requirements-test.lock updated"
